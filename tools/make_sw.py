"""Regenerate sw.js after adding lessons or audio.
Run from the project folder:  python tools/make_sw.py
It lists every app file and audio clip so the app works offline, and bumps the cache version."""
import os, time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
core = ["./", "index.html", "styles.css", "app.js", "data/lessons.js", "data/alphabet.js", "manifest.webmanifest",
        "icons/icon-192.png", "icons/icon-512.png", "icons/icon-maskable-512.png"]
audio = sorted("audio/" + f for f in os.listdir(os.path.join(ROOT, "audio")) if f.endswith(".mp3"))
img_dir = os.path.join(ROOT, "img")
audio += sorted("img/" + f for f in os.listdir(img_dir) if f.endswith(".webp")) if os.path.isdir(img_dir) else []
version = time.strftime("%Y%m%d-%H%M%S")

sw = f"""// Generated by tools/make_sw.py — do not edit by hand.
const CACHE = "davar-{version}";
const ASSETS = {core + audio!r};

self.addEventListener("install", e => {{
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(ASSETS)).then(() => self.skipWaiting()));
}});
self.addEventListener("activate", e => {{
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k !== CACHE).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
}});
self.addEventListener("fetch", e => {{
  if (e.request.method !== "GET") return;
  e.respondWith(caches.match(e.request, {{ ignoreSearch: true }}).then(hit => hit || fetch(e.request).then(res => {{
    // keep a copy of Google Fonts so text looks right offline
    if (res.ok && /fonts\\.(googleapis|gstatic)\\.com/.test(e.request.url)) {{
      const copy = res.clone(); caches.open(CACHE).then(c => c.put(e.request, copy));
    }}
    return res;
  }}).catch(() => caches.match("index.html"))));
}});
""".replace("'", '"')
open(os.path.join(ROOT, "sw.js"), "w", encoding="utf-8").write(sw)
print(f"sw.js written: {len(core) + len(audio)} files, cache davar-{version}")
